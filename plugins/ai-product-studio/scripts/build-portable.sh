#!/usr/bin/env bash
# Compiles the command + all skills + references into one tool-agnostic
# instruction file for hosts without Claude Code plugin support
# (ChatGPT, Codex, Cursor, Copilot/VS Code agents, Replit, Lovable, Bolt…).
set -euo pipefail
cd "$(dirname "$0")/.."
out=portable/AI-PRODUCT-STUDIO.md

strip_frontmatter() { awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm' "$1"; }

{
  echo "<!-- Generated by scripts/build-portable.sh — edit the skills, not this file. -->"
  echo
  echo "# AI Product Studio — Portable Instructions"
  echo
  echo "These instructions are tool-agnostic. Wherever they mention a skill (product-architect, experience-director, product-builder, product-reviewer), apply the matching section below. Wherever they mention a reference file, use the matching appendix. When the host provides stronger capabilities (browser, deploy, database, image search), use them."
  echo
  echo "---"
  echo
  strip_frontmatter commands/studio.md | sed 's/\$ARGUMENTS/(the user'"'"'s request)/'
  for s in product-architect experience-director product-builder product-reviewer; do
    echo; echo "---"; echo
    echo "# Skill: $s"
    echo
    strip_frontmatter "skills/$s/SKILL.md" | sed 's/^# /## /'
  done
  echo; echo "---"; echo
  echo "# Appendices (reference files)"
  for f in skills/*/references/*.md; do
    echo; echo "## Appendix: ${f#skills/}"; echo
    sed 's/^# /### /; s/^## /#### /' "$f"
  done
} > "$out"
echo "Wrote $out ($(wc -l < "$out") lines)"
